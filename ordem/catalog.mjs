export function findCatalogEntry(group,id){return (group==='rituals'?RITUALS:group==='weapons'?WEAPONS:CATALOG).find(x=>x.id===id)||null;}

// Dados de dano verificados no texto do livro v1.2 (Eletrocussão, p. 131 impressa).
// Nunca atribuir dano a rituais sem informação confirmada.
const VERIFIED_RITUAL_DAMAGE = Object.freeze({
  'ritual-11': Object.freeze({damage:'3d6',discenteDamage:'6d6',verdadeiroDamage:'8d6'}),
  'ritual-18': Object.freeze({damage:'2d8+2',discenteDamage:'3d8+3',verdadeiroDamage:'8d8+8'})
});
export function ritualDamageData(ritual){
  if(!ritual)return {};
  const id=ritual.catalogId||ritual.id;
  const verified=VERIFIED_RITUAL_DAMAGE[id]||{};
  return {
    damage:ritual.damage||ritual.normalDamage||verified.damage||'',
    discenteDamage:ritual.discenteDamage||verified.discenteDamage||'',
    verdadeiroDamage:ritual.verdadeiroDamage||verified.verdadeiroDamage||''
  };
}

